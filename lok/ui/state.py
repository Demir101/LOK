"""Streamlit session helpers: cached services, stable state keys and page navigation.

All session-state keys used by LOK start with ``lok_`` so they never collide with
widget keys generated by Streamlit.
"""

from __future__ import annotations

from typing import Any

import streamlit as st

from lok.config import Settings
from lok.services.container import AppServices, create_services

# Stable session-state keys -------------------------------------------------------
ACTIVE_EVALUATION = "lok_active_evaluation"
START_SCENARIO = "lok_start_scenario"
LIBRARY_SELECTED = "lok_library_selected"
HISTORY_SELECTED = "lok_history_selected"
COMPARE_A = "lok_compare_a"
COMPARE_B = "lok_compare_b"
BUILDER_DRAFT = "lok_builder_draft"
BUILDER_LOAD_REQUEST = "lok_builder_load_request"
RESPONSE_DRAFTS = "lok_response_drafts"
FLASH = "lok_flash"
PAGES = "lok_pages"


@st.cache_resource(show_spinner="Initialising the local database…")
def _services(db_path: str) -> AppServices:
    from pathlib import Path

    return create_services(Path(db_path))


def settings() -> Settings:
    return Settings.load()


def services() -> AppServices:
    """Return the application services (database initialised and seeded once per process)."""
    return _services(str(settings().db_path))


def flash(message: str, kind: str = "success") -> None:
    """Queue a message to show after the next rerun (survives page switches)."""
    st.session_state.setdefault(FLASH, []).append((kind, message))


def show_flashes() -> None:
    for kind, message in st.session_state.pop(FLASH, []):
        getattr(st, kind, st.info)(message)


def register_pages(pages: dict[str, Any]) -> None:
    st.session_state[PAGES] = pages


def go(page_key: str, **state: Any) -> None:
    """Set state values and switch to another page."""
    for key, value in state.items():
        st.session_state[key] = value
    pages = st.session_state.get(PAGES, {})
    if page_key in pages:
        st.switch_page(pages[page_key])
    st.rerun()
